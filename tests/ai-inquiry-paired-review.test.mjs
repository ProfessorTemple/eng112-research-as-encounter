import assert from 'node:assert/strict';
import {blindPairs,pairedReport} from './ai-inquiry-paired-review.mjs';
const cases=[{id:'x',passage:'A creek',notes:[]},{id:'y',passage:'A garden'}];
const local=cases.map(c=>({id:c.id,output:'local '+c.id}));
const model=cases.map(c=>({id:c.id,output:'model '+c.id}));
const {packet,mapping}=blindPairs(cases,local,model,id=>id==='x'?'A':'B');
assert.equal(packet[0].A,'local x');assert.equal(packet[1].A,'model y');
assert.deepEqual(Object.keys(packet[0]),['id','passage','notes','A','B']);
assert.throws(()=>blindPairs(cases,local.slice(1),model,()=> 'A'));
assert.throws(()=>blindPairs(cases,local,model,()=> 'C'));
const review=(n,criticalFailure=false)=>({scores:Object.fromEntries(['grounding','relevance','openness','culturalSensitivity','developmentalFit'].map(k=>[k,n])),criticalFailure,reason:'Synthetic test'});
const rows=[{id:'x',A:review(1),B:review(2),preference:'B'},{id:'y',A:review(2),B:review(1),preference:'A'}];
const report=pairedReport(['x','y'],mapping,rows);
assert.equal(report.meanPairedDifference,5);assert.equal(report.preference.model,2);assert.equal(report.model.eligible,true);assert.equal(report.local.eligible,false);
assert.equal(pairedReport(['x','y'],mapping,rows.slice(0,1)).complete,false);
assert.throws(()=>pairedReport(['x','y'],mapping,[rows[0],rows[0]]));
assert.equal(pairedReport(['x','y'],mapping,[{...rows[0],B:review(2,true)},rows[1]]).model.eligible,false);
assert.equal(report.requiresHumanDecision,true);
console.log('Paired review regression passed');
